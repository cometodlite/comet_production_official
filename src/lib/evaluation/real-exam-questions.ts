/** Returns hardcoded Set A as the unified ExamQuestionData format. */
export function getHardcodedSetA(): ExamQuestionData[] {
  return REAL_EXAM_QUESTIONS_SET_A.map((q): ExamQuestionData => ({
    id: String(q.id),
    type: q.type,
    text: q.text,
    choices: q.type === "choice" ? q.choices : undefined,
    correctAnswer: q.type === "choice" ? REAL_EXAM_ANSWER_KEY[q.id] : undefined,
    explanation: REAL_EXAM_EXPLANATIONS[q.id],
    modelAnswer: q.type === "written" ? REAL_EXAM_MODEL_ANSWERS[q.id] : undefined,
    rows: q.type === "written" ? q.rows : undefined,
    fixedLast: q.type === "written",
  }));
}

